"""narration.json (+ optional voice/timing.json) → src/narr.js, then script.js = narr.js + data.js + body.js

    python3 tools/narr.py

Each scene's narration is a list of sentences, each a list of subtitle lines. When voice/timing.json exists
(written by tools/voice.py) every line carries its spoken duration, so the picture follows the voice exactly;
without it the engine's reading-pace timing is used.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = json.load(open(os.path.join(ROOT, 'src', 'narration.json'), encoding='utf-8'))
tp = os.path.join(ROOT, 'voice', 'timing.json')
T = json.load(open(tp)) if os.path.exists(tp) else {}
out = {}
for sid, sents in N.items():
    flat = [l for s in sents for l in s]
    d = T.get(sid)
    out[sid] = [{'s': l, 'd': round(d[i], 3)} for i, l in enumerate(flat)] if d else flat
js = '/* generated by tools/narr.py — edit src/narration.json */\nconst NARR = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
open(os.path.join(ROOT, 'src', 'narr.js'), 'w', encoding='utf-8').write(js)
parts = [js] + [open(os.path.join(ROOT, 'src', f), encoding='utf-8').read() for f in ('data.js', 'body.js')]
open(os.path.join(ROOT, 'script.js'), 'w', encoding='utf-8').write(''.join(parts))
print('script.js', 'voice-timed' if T else 'reading-pace', sum(len(v) for v in out.values()), 'lines')
